def get_sector_from_krx_industry(symbol, industry, name=""):
    """KRX 구 산업분류 단축명(FDR KRX-DELISTING 어휘) 전용 매핑.
    오버라이드 테이블을 먼저 보고, 없으면 공통 키워드 매퍼로 폴백한다."""
    # 로봇 섹터는 산업분류가 아니라 사명 기준(KSIC에 '로봇' 업종 없음) — 상폐 로봇 기업이
    # 단축명 오버라이드('기계·장비' 등)에 선점되지 않도록 사명 판정을 먼저 거친다.
    lowered = str(name or "").lower()
    if any(kw in lowered for kw in MAPPING_RULES["로봇"]):
        return "로봇"
    ind = str(industry or "").strip()
    if ind in KRX_SHORT_INDUSTRY_OVERRIDES:
        return KRX_SHORT_INDUSTRY_OVERRIDES[ind]
    return get_sector_from_industry(symbol, ind, name)
