def sector_for_code(induty_code: Optional[str]) -> Optional[str]:
    """KSIC 코드로 정본 섹터를 찾는다(최장 접두 우선). 못 찾으면 None."""
    code = (induty_code or "").strip()
    if not code:
        return None
    for length in (5, 4, 3):
        if len(code) >= length:
            hit = KSIC_SECTOR.get(code[:length])
            if hit:
                return hit
    return None


# ── 종목 → KSIC 코드 (DART 백필 결과) ────────────────────────────────────────

_DART_PATH = Path(__file__).resolve().parent.parent.parent / "data" / "dart-industry.json"


@lru_cache(maxsize=1)
def _dart_codes() -> dict[str, str]:
    if not _DART_PATH.exists():
        return {}
    raw = json.loads(_DART_PATH.read_text(encoding="utf-8"))
    return {
        symbol: (entry.get("induty_code") or "").strip()
        for symbol, entry in raw.items()
        if entry.get("induty_code")
    }


def sector_for_symbol(symbol: str) -> Optional[str]:
    """종목의 DART 등록 업종코드로 정본 섹터를 찾는다. 코드가 없으면 None."""
    return sector_for_code(_dart_codes().get(symbol or ""))


def reload_codes() -> None:
    """DART 백필 파일을 다시 읽는다(재백필 후 호출)."""
    _dart_codes.cache_clear()
