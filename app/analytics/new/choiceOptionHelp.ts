/** 설명 풍선의 가로 예산(px)과 세로 여백. 세로 높이는 글 길이에 따라 달라지므로
 *  예산으로 잡지 않고 **그려진 뒤 실제로 재서** 자리를 정한다(예산으로 세로 중앙을
 *  맞췄더니 실제보다 높이를 크게 잡아 풍선이 칩보다 한참 위에 떴다 — 2026-08-29 신고). */
export const HELP_BUBBLE_WIDTH = 288;
const HELP_BUBBLE_GAP = 8;
const HELP_BUBBLE_MARGIN = 12;
// 풍선 윗변을 아이콘보다 이만큼 위로 올린다 — 칩 윗변과 나란히 서서 '칩 오른쪽 위'로 읽힌다.
const HELP_BUBBLE_RISE = 6;

type Rect = { top: number; left: number; right: number };

/** 화면 폭에 맞춘 풍선 가로 크기. 높이를 재기 전에 정해야 한다(폭이 줄글 줄 수를 정한다). */
export function helpBubbleWidth(viewportWidth: number): number {
  return Math.min(HELP_BUBBLE_WIDTH, viewportWidth - HELP_BUBBLE_MARGIN * 2);
}

/** 물음표 아이콘 **바로 오른쪽 위**에 풍선을 놓을 화면 좌표(fixed 기준).
 *
 *  오른쪽이 모자라면 왼쪽으로 넘기고, 마지막에 가로·세로 모두 화면 안으로 당긴다 —
 *  칩 목록은 화면 아래에 고정된 카드 안에도 뜨므로(되묻기 도킹) 아래쪽 칩의 풍선이
 *  화면 밖으로 나가기 쉽다. */
export function placeHelpBubble(
  trigger: Rect,
  viewportWidth: number,
  viewportHeight: number,
  bubbleHeight: number,
): { top: number; left: number; width: number } {
  const width = helpBubbleWidth(viewportWidth);
  const rightSide = trigger.right + HELP_BUBBLE_GAP;
  const left =
    rightSide + width <= viewportWidth - HELP_BUBBLE_MARGIN
      ? rightSide
      : trigger.left - HELP_BUBBLE_GAP - width;
  const clamp = (value: number, max: number) =>
    Math.max(HELP_BUBBLE_MARGIN, Math.min(value, Math.max(HELP_BUBBLE_MARGIN, max)));
  return {
    left: clamp(left, viewportWidth - HELP_BUBBLE_MARGIN - width),
    top: clamp(trigger.top - HELP_BUBBLE_RISE, viewportHeight - HELP_BUBBLE_MARGIN - bubbleHeight),
    width,
  };
}
