function exampleByTitle(title: string): string {
  const example = EXAMPLES.find((e) => e.title === title);
  // Fail Fast — 예시 제목이 바뀌면 빌드·테스트에서 바로 드러나야 한다(조용히 버튼이 사라지지 않게).
  if (!example) throw new Error(`지표 사전: 전략 예시 '${title}'를 찾을 수 없습니다`);
  return example.prompt;
}

