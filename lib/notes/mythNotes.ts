import type { GuideArticle, GuideFaq, GuideSection } from "@/lib/guide/articles";

type Row = [string, string];

type Result = {
  period: string;
  tradingDays?: string;
  start?: string;
  end?: string;
  ret: string;
  cagr: string;
  realCagr?: string;
  mdd: string;
  sharpe?: string;
  win: string;
  pf?: string;
  trades: string;
  avgWin?: string;
  avgLoss?: string;
  hold?: string;
  lossStreak?: string;
  bench: string;
};

type Myth = {
  n: number;
  slug: string;
  /** 계산일 = 게시일(YYYY-MM-DD). */
  date: string;
  engine: string;
  market: string;
  myth: string;
  /** 글 제목에 붙는 규칙 한 줄 설명. */
  rule: string;
  /** 규칙이 무엇인지 두세 문장으로. */
  intro: string[];
  /** 입력 문장(원문). 없으면 예시 이름만 적는다. */
  input?: string[];
  inputName?: string;
  /** 해석된 조건·설정. */
  conditions: string[];
  /** 문장에 없어 화면의 선택지로 정한 값. */
  chosen?: string;
  result: Result;
  exits?: { rows: string[][]; note?: string };
  /** 가격·재무 데이터로 다시 계산해 대조한 항목. */
  checks: string[];
  /** 눈에 띈 거래·구조 관찰(종목명 없이). */
  cases?: string[];
  /** 해석·엔진 관련 주의. */
  caveats?: string[];
  summary: string;
  related: string[];
};

const COMMON_COST =
  "수수료 0.015%, 슬리피지 0.05%, 거래세 0.23%→0.15%(시행일 기준), 배당소득세 15.4%를 반영했고 체결은 신호 다음 거래일 시가입니다.";

function resultRows(r: Result): Row[] {
  const rows: Row[] = [["기간", r.tradingDays ? `${r.period} (${r.tradingDays})` : r.period]];
  if (r.start && r.end) rows.push(["자산", `${r.start} → ${r.end}`]);
  rows.push(["투자 수익률", r.ret], ["CAGR", r.cagr]);
  if (r.realCagr) rows.push(["물가 반영 실질 CAGR", r.realCagr]);
  rows.push(["최대 낙폭", r.mdd]);
  if (r.sharpe) rows.push(["샤프 / 소티노", r.sharpe]);
  rows.push(["거래 수", r.trades], ["승률", r.win]);
  if (r.pf) rows.push(["손익비", r.pf]);
  if (r.avgWin) rows.push(["평균 수익 거래", r.avgWin]);
  if (r.avgLoss) rows.push(["평균 손실 거래", r.avgLoss]);
  if (r.hold) rows.push(["평균 보유", r.hold]);
  if (r.lossStreak) rows.push(["최대 연속 손실", r.lossStreak]);
  rows.push(["같은 기간 벤치마크", r.bench]);
  return rows;
}

function buildNote(m: Myth): GuideArticle {
  const footnote = `${m.market}, ${m.result.period}, 신호 다음 거래일 시가 체결, 수수료 0.015%·슬리피지 0.05%. 널스탁 백테스트 엔진 v${m.engine}으로 ${m.date}에 계산했습니다.`;

  const sections: GuideSection[] = [
    {
      heading: "검증한 속설과 규칙",
      paragraphs: [
        `속설 검증 시리즈 ${m.n}번째 기록입니다. 검증한 말은 “${m.myth}”입니다. 속설을 그대로 코드로 옮길 수는 없어서, 아래 규칙 하나를 정해 과거 데이터에 적용했습니다. 이 노트는 그 규칙이 맞는지 틀린지 판정하지 않고, 한 가지 설정에서 관측된 값을 기록합니다.`,
        ...m.intro,
      ],
    },
    {
      heading: "입력한 문장과 해석된 조건",
      paragraphs: [
        ...(m.input
          ? ["널스탁에 아래 문장을 그대로 입력했습니다.", ...m.input.map((s) => `“${s}”`)]
          : [`널스탁 예시 전략 “${m.inputName}”을 입력했습니다. 아래는 이 전략이 해석된 조건입니다.`]),
        ...(m.chosen ? [m.chosen] : []),
      ],
      bullets: m.conditions,
    },
    {
      heading: "결과",
      paragraphs: [
        `${m.result.period} 구간에서 관측된 값입니다. ${COMMON_COST} 전략과 벤치마크는 구성과 규칙이 다르므로 표의 차이는 우열을 뜻하지 않습니다.`,
      ],
      table: {
        caption: `속설 검증 #${m.n} — 백테스트 결과`,
        headers: ["지표", "값"],
        rows: resultRows(m.result),
        footnote,
      },
    },
  ];

  if (m.exits) {
    sections.push({
      heading: "청산 내역",
      paragraphs: [
        "거래가 끝난 이유별로 건수와 합산 손익을 나눴습니다." + (m.exits.note ? ` ${m.exits.note}` : ""),
      ],
      table: {
        caption: `속설 검증 #${m.n} — 청산 방식별 내역`,
        headers: ["청산 방식", "건수", "비고"],
        rows: m.exits.rows,
        footnote,
      },
    });
  }

  sections.push({
    heading: "직접 다시 계산해 대조한 것",
    paragraphs: [
      "화면의 결과를 그대로 믿지 않고, 매수·청산 기록을 가격(·재무) 데이터에서 독립적으로 다시 계산해 신호가 규칙대로 나왔는지 확인했습니다.",
    ],
    bullets: m.checks,
  });

  if (m.cases && m.cases.length > 0) {
    sections.push({ heading: "눈에 띈 거래", paragraphs: m.cases });
  }

  sections.push({
    heading: "읽을 때 주의할 점",
    paragraphs: [
      "이 기록은 특정 유니버스·기간·파라미터 한 가지 조합의 과거 시뮬레이션 결과입니다. 다른 기간이나 값에서는 다른 결과가 나올 수 있고, 한 규칙의 결과가 속설 전체의 성립 여부를 말해 주지도 않습니다. 미래 수익은 보장되지 않습니다.",
      ...(m.caveats ?? []),
    ],
  });

  const faq: GuideFaq[] = [
    {
      question: `이 결과로 “${m.myth}”가 맞다 또는 틀리다고 말할 수 있나요?`,
      answer:
        "아닙니다. 속설 하나를 규칙 하나로 옮겨 한 유니버스·한 기간에서 계산한 값이며, 규칙·기간·종목 수를 바꾸면 결과가 달라질 수 있습니다. 관측된 숫자를 기록한 것일 뿐 성립 여부를 판정하지 않고, 미래 수익은 보장되지 않습니다.",
    },
    {
      question: "표의 벤치마크와의 차이는 무엇을 뜻하나요?",
      answer: `같은 기간 지수 ETF의 수익률(${m.result.bench})과 전략 수익률(${m.result.ret})을 표시값 그대로 비교하는 용도입니다. 전략은 조건에 맞는 종목만 일정 수 보유하고 ETF는 지수 전체를 보유하므로 구성과 규칙이 달라 우열을 가리는 값은 아닙니다.`,
    },
  ];

  return {
    slug: m.slug,
    title: `속설 검증 #${m.n} — ${m.rule} 백테스트 기록`,
    description: `“${m.myth}”를 ${m.market} ${m.result.period} 구간의 규칙 하나로 옮겨 계산한 기록입니다. 입력 문장, 해석된 조건, 결과 수치, 가격 데이터 재계산 대조를 담았습니다.`,
    summary: m.summary,
    published: m.date,
    updated: m.date,
    sections,
    related: m.related,
    faq,
  };
}

